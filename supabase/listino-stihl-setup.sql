-- ============================================================
-- AGRIDESK / AGRIMAG - LISTINO STIHL
-- ------------------------------------------------------------
-- Listino unico degli articoli STIHL, caricato dai file Excel del fornitore (OPG, OPM, ...).
--   stihl_articoli  una riga per CODICE articolo STIHL (es. GA01-011-6910)
--                   prezzi IVA ESCLUSA come nel file: listino e netto (prezzo promo)
--                   ricarico % deciso al caricamento (di default 30)
--                   articolo_id = articolo collegato nel Listino Vendite (facoltativo)
--   stihl_fonti     un record per ogni file caricato (nome, foglio, riga intestazioni,
--                   colonne scelte, ricarico): serve anche a riproporre le scelte la volta dopo
-- Se lo stesso codice c'e' in piu' file vale l'ULTIMO caricato.
--
-- Chi puo' fare cosa (tabella user_roles):
--   vedere il listino: admin e operatori (stihl_puo_vedere)
--   caricare file, EAN, cambiare ricarico e collegare/creare articoli: SOLO admin (stihl_puo_caricare)
--   Il collegamento con il Listino Vendite passa dalla funzione stihl_collega().
--
-- Come si usa: Supabase > SQL Editor > New query, incolla tutto e premi Run.
-- Si puo' rieseguire senza problemi.
-- ============================================================

create table if not exists public.stihl_fonti (
    id                 bigint generated by default as identity primary key,
    nome               text not null,            -- es. OPG 2026
    file_nome          text,
    foglio             text,
    riga_intestazioni  integer,
    colonne            jsonb,                    -- { codice: 'Codice', descrizione: '...', ... } (testi delle intestazioni)
    ricarico           numeric(6,2) not null default 30,
    righe              integer,                  -- articoli caricati da questo file
    caricato_il        timestamptz not null default now(),
    caricato_da        text
);

create table if not exists public.stihl_articoli (
    id             bigint generated by default as identity primary key,
    codice         text not null unique,         -- codice articolo STIHL (non e' il codice a barre)
    descrizione    text,
    categoria      text,
    listino_escl   numeric(12,4),                -- listino IVA esclusa
    netto_escl     numeric(12,4),                -- nostro netto IVA esclusa (prezzo promo)
    ricarico       numeric(6,2) not null default 30,
    fonte_id       bigint references public.stihl_fonti(id) on delete set null,
    articolo_id    bigint references public.listino_articoli(id) on delete set null,
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now(),
    updated_by     text
);

-- Codice a barre (EAN/UPC) preso da un catalogo STIHL (es. Superlistino): solo per gli articoli del listino STIHL
alter table public.stihl_articoli add column if not exists ean text;

create index if not exists stihl_articoli_fonte_idx on public.stihl_articoli (fonte_id);
create index if not exists stihl_articoli_articolo_idx on public.stihl_articoli (articolo_id);

-- ------------------------------------------------------------
-- Permessi
-- ------------------------------------------------------------
create or replace function public.stihl_puo_vedere()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1 from public.user_roles
        where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
          and role in ('admin', 'operatore')
    );
$$;

create or replace function public.stihl_puo_caricare()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1 from public.user_roles
        where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
          and role = 'admin'
    );
$$;

alter table public.stihl_fonti enable row level security;
alter table public.stihl_articoli enable row level security;

drop policy if exists "stihl_fonti_lettura" on public.stihl_fonti;
create policy "stihl_fonti_lettura" on public.stihl_fonti
    for select to authenticated using (public.stihl_puo_vedere());
drop policy if exists "stihl_fonti_scrittura" on public.stihl_fonti;
create policy "stihl_fonti_scrittura" on public.stihl_fonti
    for all to authenticated
    using (public.stihl_puo_caricare())
    with check (public.stihl_puo_caricare());

drop policy if exists "stihl_articoli_lettura" on public.stihl_articoli;
create policy "stihl_articoli_lettura" on public.stihl_articoli
    for select to authenticated using (public.stihl_puo_vedere());
drop policy if exists "stihl_articoli_scrittura" on public.stihl_articoli;
create policy "stihl_articoli_scrittura" on public.stihl_articoli
    for all to authenticated
    using (public.stihl_puo_caricare())
    with check (public.stihl_puo_caricare());

-- ------------------------------------------------------------
-- Collegamento con il Listino Vendite (solo admin):
-- cambia SOLO articolo_id, niente prezzi
-- ------------------------------------------------------------
create or replace function public.stihl_collega(p_id bigint, p_articolo bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
    if not public.stihl_puo_caricare() then
        raise exception 'Non autorizzato';
    end if;
    update public.stihl_articoli
       set articolo_id = p_articolo,
           updated_at = now(),
           updated_by = coalesce(auth.jwt() ->> 'email', updated_by)
     where id = p_id;
end;
$$;

revoke all on function public.stihl_collega(bigint, bigint) from public;
grant execute on function public.stihl_collega(bigint, bigint) to authenticated;

-- Controllo finale: devono comparire le due tabelle
select table_name from information_schema.tables
where table_schema = 'public' and table_name in ('stihl_fonti', 'stihl_articoli');
