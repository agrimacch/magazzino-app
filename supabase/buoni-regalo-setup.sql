-- ------------------------------------------------------------
-- Tabella buoni_regalo: un buono regalo per riga, con numero
-- progressivo che riparte da 1 ogni anno (2026/1, 2026/2 ... 2027/1),
-- come gli ordini clienti.
--
-- Chi puo' fare cosa (PER ORA): solo admin -> funzione buoni_puo_gestire().
-- Per aprire anche agli operatori, piu' avanti, basta eseguire:
--   create or replace function public.buoni_puo_gestire()
--   returns boolean language sql stable security definer set search_path = public
--   as $f$ select public.puo_gestire_macchine(); $f$;
--
-- Come si usa: Supabase > SQL Editor > New query, incolla tutto e Run.
-- Si puo' rieseguire senza problemi (non cancella dati).
-- ============================================================

create table if not exists public.buoni_regalo (
    id              bigint generated by default as identity primary key,
    anno            integer not null,
    numero          integer not null,
    data            date not null default ((now() at time zone 'Europe/Rome')::date),   -- data di emissione
    operatore       text,                      -- chi ha fatto il buono (iniziali)
    cliente         text not null,             -- chi compra il buono
    telefono        text not null default '',
    intestato_a     text,                      -- chi riceve il regalo (vuoto = il cliente)
    importo         numeric(12,2) not null check (importo > 0),
    scadenza        date not null,
    note            text,
    utilizzato_at   timestamptz,               -- buono usato in negozio
    utilizzato_note text,
    annullato_at    timestamptz,
    created_at      timestamptz not null default now(),
    created_by      text,
    updated_at      timestamptz not null default now(),
    updated_by      text,
    unique (anno, numero)
);

create index if not exists buoni_regalo_anno_idx on public.buoni_regalo (anno);

-- PDF su Google Drive (v6.4.0, come gli ordini clienti: funzione buoni-drive)
alter table public.buoni_regalo add column if not exists drive_url text;
alter table public.buoni_regalo add column if not exists drive_file_id text;
alter table public.buoni_regalo add column if not exists drive_salvato_at timestamptz;

-- Chi puo' gestire i buoni (per ora solo admin)
create or replace function public.buoni_puo_gestire()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select public.is_admin();
$$;

alter table public.buoni_regalo enable row level security;

drop policy if exists "buoni_regalo_tutto" on public.buoni_regalo;
create policy "buoni_regalo_tutto" on public.buoni_regalo
    for all to authenticated
    using (public.buoni_puo_gestire())
    with check (public.buoni_puo_gestire());

-- Tempo reale: se un collega aggiunge un buono, l'elenco si aggiorna da solo
do $$
begin
    if not exists (
        select 1 from pg_publication_tables
        where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'buoni_regalo'
    ) then
        alter publication supabase_realtime add table public.buoni_regalo;
    end if;
end $$;

-- Controllo finale: deve comparire 1 regola con realtime = true
select
    p.policyname as regola,
    p.cmd as operazione,
    exists (
        select 1 from pg_publication_tables r
        where r.pubname = 'supabase_realtime' and r.tablename = 'buoni_regalo'
    ) as realtime
from pg_policies p
where p.tablename = 'buoni_regalo';
