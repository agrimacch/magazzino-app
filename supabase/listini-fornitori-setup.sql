-- ============================================================
-- AGRIDESK - LISTINI FORNITORI (listini "paralleli" al Listino Agrimacch, per piu' fornitori)
-- ------------------------------------------------------------
-- Generalizza il Listino STIHL: ogni FORNITORE (STIHL, domani altri) ha piu' LISTINI
-- (es. OPG, OPM) ognuno con il suo file, la sua scadenza e i suoi prezzi.
--
--   lf_fornitori  il fornitore (nome, marchio da usare nel Listino Agrimacch, ricarico di partenza)
--   lf_listini    un listino del fornitore: nome, SCADENZA, file/foglio/riga/colonne dell'ultimo
--                 caricamento (riproposte la volta dopo), ricarico %
--   lf_articoli   una riga per CODICE articolo del fornitore: descrizione, categoria, EAN (codice a barre)
--                 e collegamento con il Listino Agrimacch (articolo_id). Valgono per TUTTI i listini.
--   lf_prezzi     il prezzo di un articolo in un listino (listino e netto IVA esclusa)
--
-- Un nuovo file per un listino lo SOSTITUISCE per intero (funzione lf_carica_listino):
-- i prezzi vecchi di quel listino spariscono, gli articoli (con EAN e collegamento) restano.
-- Lo stesso codice puo' stare in piu' listini, ognuno con il suo prezzo.
--
-- Chi puo' fare cosa (tabella user_roles):
--   vedere, Collega / Crea nel Listino Agrimacch: admin e operatori (lf_puo_vedere, lf_collega)
--   fornitori, caricare file, scadenze, ricarico, EAN, eliminare: SOLO admin (lf_puo_caricare)
--
-- All'avvio copia i dati del vecchio Listino STIHL (stihl_articoli / stihl_fonti, che NON vengono toccati):
-- fornitore STIHL, un listino per ogni nome di file (OPG, OPM...), articoli con EAN e collegamenti, prezzi.
-- Attenzione: il vecchio listino teneva UN solo prezzo per codice (l'ultimo file caricato): i codici che
-- erano in piu' file finiscono solo nell'ultimo. Per averli in tutti, ricarica i file nei listini nuovi.
--
-- Come si usa: Supabase > SQL Editor > New query, incolla tutto e premi Run.
-- Si puo' rieseguire senza problemi (la copia dal vecchio listino non crea doppioni).
-- ============================================================

create table if not exists public.lf_fornitori (
    id               bigint generated by default as identity primary key,
    nome             text not null unique,            -- es. STIHL
    marchio          text,                            -- marchio nel Listino Agrimacch (Crea); vuoto = nome
    ricarico_default numeric(6,2) not null default 30,
    created_at       timestamptz not null default now(),
    created_by       text
);

create table if not exists public.lf_listini (
    id                 bigint generated by default as identity primary key,
    fornitore_id       bigint not null references public.lf_fornitori(id) on delete cascade,
    nome               text not null,                 -- es. OPG 2026
    scadenza           date,                          -- fino a quando vale
    file_nome          text,
    foglio             text,
    riga_intestazioni  integer,
    colonne            jsonb,                         -- titoli delle colonne scelte (riproposte la volta dopo)
    ricarico           numeric(6,2) not null default 30,
    righe              integer,
    caricato_il        timestamptz not null default now(),
    caricato_da        text,
    unique (fornitore_id, nome)
);

create table if not exists public.lf_articoli (
    id            bigint generated by default as identity primary key,
    fornitore_id  bigint not null references public.lf_fornitori(id) on delete cascade,
    codice        text not null,                      -- codice articolo del fornitore
    descrizione   text,
    categoria     text,
    ean           text,                               -- codice a barre (da un catalogo del fornitore)
    articolo_id   bigint references public.listino_articoli(id) on delete set null,   -- Listino Agrimacch
    created_at    timestamptz not null default now(),
    updated_at    timestamptz not null default now(),
    updated_by    text,
    unique (fornitore_id, codice)
);
create index if not exists lf_articoli_articolo_idx on public.lf_articoli (articolo_id);
create index if not exists lf_articoli_ean_idx on public.lf_articoli (ean);

create table if not exists public.lf_prezzi (
    id            bigint generated by default as identity primary key,
    listino_id    bigint not null references public.lf_listini(id) on delete cascade,
    articolo_id   bigint not null references public.lf_articoli(id) on delete cascade,
    listino_escl  numeric(12,4),                      -- listino IVA esclusa
    netto_escl    numeric(12,4),                      -- nostro netto IVA esclusa (prezzo promo)
    unique (listino_id, articolo_id)
);
create index if not exists lf_prezzi_articolo_idx on public.lf_prezzi (articolo_id);

-- ------------------------------------------------------------
-- Permessi
-- ------------------------------------------------------------
create or replace function public.lf_puo_vedere()
returns boolean language sql stable security definer set search_path = public as $$
    select exists (
        select 1 from public.user_roles
        where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
          and role in ('admin', 'operatore')
    );
$$;

create or replace function public.lf_puo_caricare()
returns boolean language sql stable security definer set search_path = public as $$
    select exists (
        select 1 from public.user_roles
        where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
          and role = 'admin'
    );
$$;

alter table public.lf_fornitori enable row level security;
alter table public.lf_listini enable row level security;
alter table public.lf_articoli enable row level security;
alter table public.lf_prezzi enable row level security;

do $$
declare t text;
begin
    foreach t in array array['lf_fornitori', 'lf_listini', 'lf_articoli', 'lf_prezzi'] loop
        execute format('drop policy if exists %I on public.%I', t || '_lettura', t);
        execute format('create policy %I on public.%I for select to authenticated using (public.lf_puo_vedere())', t || '_lettura', t);
        execute format('drop policy if exists %I on public.%I', t || '_scrittura', t);
        execute format('create policy %I on public.%I for all to authenticated using (public.lf_puo_caricare()) with check (public.lf_puo_caricare())', t || '_scrittura', t);
    end loop;
end;
$$;

-- ------------------------------------------------------------
-- Collegamento con il Listino Agrimacch (admin e operatori): cambia SOLO articolo_id
-- ------------------------------------------------------------
create or replace function public.lf_collega(p_id bigint, p_articolo bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
    if not public.lf_puo_vedere() then
        raise exception 'Non autorizzato';
    end if;
    update public.lf_articoli
       set articolo_id = p_articolo, updated_at = now(),
           updated_by = coalesce(auth.jwt() ->> 'email', updated_by)
     where id = p_id;
end;
$$;
revoke all on function public.lf_collega(bigint, bigint) from public;
grant execute on function public.lf_collega(bigint, bigint) to authenticated;

-- Collega / Crea: il codice del fornitore passa nel codice articolo del Listino Agrimacch (se vuoto)
alter table public.listino_articoli add column if not exists codice_articolo text;
create or replace function public.lf_codice_al_listino()
returns trigger language plpgsql security definer set search_path = public as $$
begin
    if new.articolo_id is not null and (tg_op = 'INSERT' or new.articolo_id is distinct from old.articolo_id) then
        update public.listino_articoli
           set codice_articolo = new.codice
         where id = new.articolo_id
           and (codice_articolo is null or btrim(codice_articolo) = '');
    end if;
    return new;
end;
$$;
drop trigger if exists lf_codice_al_listino on public.lf_articoli;
create trigger lf_codice_al_listino
    after insert or update of articolo_id on public.lf_articoli
    for each row execute function public.lf_codice_al_listino();

-- ------------------------------------------------------------
-- Caricamento di un file in un listino (solo admin), tutto insieme:
--   p_listino = { id (vuoto = nuovo listino), nome, scadenza, file_nome, foglio, riga, colonne, ricarico }
--   p_righe   = [ { codice, descrizione, categoria, listino_escl, netto_escl } ]
-- Articoli: nuovi aggiunti, esistenti aggiornati (descrizione; categoria solo se c'e'). EAN e collegamento restano.
-- Prezzi del listino: SOSTITUITI per intero.
-- ------------------------------------------------------------
create or replace function public.lf_carica_listino(p_fornitore bigint, p_listino jsonb, p_righe jsonb)
returns bigint language plpgsql security definer set search_path = public as $$
declare
    v_id bigint;
    v_chi text := coalesce(auth.jwt() ->> 'email', '');
begin
    if not public.lf_puo_caricare() then
        raise exception 'Non autorizzato';
    end if;
    if nullif(p_listino ->> 'id', '') is not null then
        v_id := (p_listino ->> 'id')::bigint;
        update public.lf_listini set
            nome = p_listino ->> 'nome',
            scadenza = nullif(p_listino ->> 'scadenza', '')::date,
            file_nome = p_listino ->> 'file_nome',
            foglio = p_listino ->> 'foglio',
            riga_intestazioni = nullif(p_listino ->> 'riga', '')::integer,
            colonne = p_listino -> 'colonne',
            ricarico = coalesce(nullif(p_listino ->> 'ricarico', '')::numeric, 30),
            righe = jsonb_array_length(p_righe),
            caricato_il = now(),
            caricato_da = v_chi
        where id = v_id and fornitore_id = p_fornitore;
        if not found then
            raise exception 'Listino non trovato';
        end if;
    else
        insert into public.lf_listini (fornitore_id, nome, scadenza, file_nome, foglio, riga_intestazioni, colonne, ricarico, righe, caricato_da)
        values (p_fornitore, p_listino ->> 'nome', nullif(p_listino ->> 'scadenza', '')::date, p_listino ->> 'file_nome',
                p_listino ->> 'foglio', nullif(p_listino ->> 'riga', '')::integer, p_listino -> 'colonne',
                coalesce(nullif(p_listino ->> 'ricarico', '')::numeric, 30), jsonb_array_length(p_righe), v_chi)
        returning id into v_id;
    end if;

    insert into public.lf_articoli (fornitore_id, codice, descrizione, categoria, updated_at, updated_by)
    select p_fornitore, r ->> 'codice', r ->> 'descrizione', nullif(r ->> 'categoria', ''), now(), v_chi
    from jsonb_array_elements(p_righe) r
    on conflict (fornitore_id, codice) do update set
        descrizione = excluded.descrizione,
        categoria = coalesce(excluded.categoria, public.lf_articoli.categoria),
        updated_at = now(),
        updated_by = excluded.updated_by;

    delete from public.lf_prezzi where listino_id = v_id;
    insert into public.lf_prezzi (listino_id, articolo_id, listino_escl, netto_escl)
    select v_id, a.id, nullif(r ->> 'listino_escl', '')::numeric, nullif(r ->> 'netto_escl', '')::numeric
    from jsonb_array_elements(p_righe) r
    join public.lf_articoli a on a.fornitore_id = p_fornitore and a.codice = r ->> 'codice'
    on conflict (listino_id, articolo_id) do nothing;

    return v_id;
end;
$$;
revoke all on function public.lf_carica_listino(bigint, jsonb, jsonb) from public;
grant execute on function public.lf_carica_listino(bigint, jsonb, jsonb) to authenticated;

-- ------------------------------------------------------------
-- Copia dal vecchio Listino STIHL (se c'e'). Non tocca le tabelle stihl_*.
-- ------------------------------------------------------------
do $$
declare v_f bigint;
begin
    if to_regclass('public.stihl_articoli') is null or to_regclass('public.stihl_fonti') is null then
        return;
    end if;
    insert into public.lf_fornitori (nome, marchio, ricarico_default) values ('STIHL', 'STIHL', 30)
    on conflict (nome) do nothing;
    select id into v_f from public.lf_fornitori where nome = 'STIHL';

    -- un listino per ogni nome di file (l'ultimo caricamento con quel nome)
    insert into public.lf_listini (fornitore_id, nome, file_nome, foglio, riga_intestazioni, colonne, ricarico, righe, caricato_il, caricato_da)
    select distinct on (f.nome) v_f, f.nome, f.file_nome, f.foglio, f.riga_intestazioni, f.colonne, f.ricarico, f.righe, f.caricato_il, f.caricato_da
    from public.stihl_fonti f
    order by f.nome, f.id desc
    on conflict (fornitore_id, nome) do nothing;

    insert into public.lf_articoli (fornitore_id, codice, descrizione, categoria, ean, articolo_id, updated_at, updated_by)
    select v_f, s.codice, s.descrizione, s.categoria, s.ean, s.articolo_id, s.updated_at, s.updated_by
    from public.stihl_articoli s
    on conflict (fornitore_id, codice) do nothing;

    insert into public.lf_prezzi (listino_id, articolo_id, listino_escl, netto_escl)
    select l.id, a.id, s.listino_escl, s.netto_escl
    from public.stihl_articoli s
    join public.stihl_fonti f on f.id = s.fonte_id
    join public.lf_listini l on l.fornitore_id = v_f and l.nome = f.nome
    join public.lf_articoli a on a.fornitore_id = v_f and a.codice = s.codice
    on conflict (listino_id, articolo_id) do nothing;
end;
$$;

-- Controllo finale: fornitori, listini, articoli e prezzi
select 'fornitori' as cosa, count(*) as quanti from public.lf_fornitori
union all select 'listini', count(*) from public.lf_listini
union all select 'articoli', count(*) from public.lf_articoli
union all select 'prezzi', count(*) from public.lf_prezzi;
