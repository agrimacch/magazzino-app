-- ============================================================
-- AGRIMAG - NOTIFICHE LISTINO VENDITE (v4.9.0)
-- ------------------------------------------------------------
-- Crea la tabella delle notifiche (una riga per ogni modifica
-- al listino: modifica articolo, nuovo, cancellato, ripristinato,
-- import Excel) e la collega al "tempo reale" di Supabase, cosi'
-- la campanella si aggiorna da sola su tutti i dispositivi aperti.
--
-- Come si usa: Supabase > SQL Editor > New query, incolla tutto
-- e premi Run. Si puo' rieseguire senza problemi.
-- ============================================================

create table if not exists public.listino_notifiche (
    id           bigint generated by default as identity primary key,
    created_at   timestamptz not null default now(),
    utente       text not null,          -- email di chi ha fatto la modifica
    utente_nome  text,                   -- iniziali (da Gestione Utenti)
    tipo         text not null,          -- MODIFICA / NUOVO / CANCELLATO / RIPRISTINATO / IMPORT
    titolo       text not null,          -- es. "HONDA HRG416PK (TOSAERBA)"
    righe        jsonb not null default '[]'::jsonb,  -- dettagli: [{e: etichetta, v: valore, n: true se e' un netto}]
    articolo_id  bigint,                 -- articolo coinvolto (vuoto per gli import)
    cerca        text                    -- testo da mettere nella ricerca del listino ("Vai all'articolo")
);

create index if not exists listino_notifiche_created_at_idx
    on public.listino_notifiche (created_at desc);

-- ------------------------------------------------------------
-- Sicurezza (RLS): solo utenti collegati.
-- Tutti leggono tutto; ognuno puo' scrivere solo notifiche
-- a proprio nome (non si puo' fingere di essere un altro).
-- Nessuno puo' modificare o cancellare le notifiche dall'app.
-- ------------------------------------------------------------
alter table public.listino_notifiche enable row level security;

drop policy if exists "listino_notifiche_lettura" on public.listino_notifiche;
create policy "listino_notifiche_lettura"
    on public.listino_notifiche
    for select
    to authenticated
    using (true);

drop policy if exists "listino_notifiche_inserimento" on public.listino_notifiche;
create policy "listino_notifiche_inserimento"
    on public.listino_notifiche
    for insert
    to authenticated
    with check (lower(utente) = lower(coalesce(auth.jwt() ->> 'email', '')));

-- ------------------------------------------------------------
-- Tempo reale: la tabella entra nella pubblicazione "supabase_realtime"
-- (solo se non c'e' gia', cosi' lo script si puo' rieseguire)
-- ------------------------------------------------------------
do $$
begin
    if not exists (
        select 1 from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'listino_notifiche'
    ) then
        alter publication supabase_realtime add table public.listino_notifiche;
    end if;
end $$;

-- ------------------------------------------------------------
-- Controllo finale: devono comparire 2 righe di regole
-- e "realtime = true"
-- ------------------------------------------------------------
select
    p.policyname as regola,
    p.cmd as operazione,
    exists (
        select 1 from pg_publication_tables
        where pubname = 'supabase_realtime' and tablename = 'listino_notifiche'
    ) as realtime
from pg_policies p
where p.tablename = 'listino_notifiche'
order by p.policyname;
