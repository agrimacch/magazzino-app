-- ============================================================
-- AGRIDESK - ORDINI MACCHINE AL FORNITORE (il "libro" con i divisori per marchio)
-- ------------------------------------------------------------
-- Richiede che siano gia' stati eseguiti inventario-macchine-setup.sql e ordini-clienti-setup.sql
--
--   macchine_of_sezioni   le sezioni dentro un marchio (es. STIHL > OPG, TRATTORINI 2026).
--                         La sezione ORDINI NORMALE non si salva: e' quella "senza sezione".
--   macchine_of_ordini    un ordine fatto al fornitore: marchio, sezione, data, iniziali di chi
--                         l'ha fatto, consegna prevista (testo libero, per i prestagionali), note
--   macchine_pezzi        + colonna ordine_fornitore_id (la macchina ordinata con quell'ordine)
--
-- Una macchina ORDINATA senza cliente = ordinata in un prestagionale e ancora libera:
-- il primo ordine cliente di quel modello la prende ("in arrivo").
-- Le macchine arrivate tengono il collegamento all'ordine fornitore (spunta nel libro).
--
-- Permessi: come l'inventario macchine (funzione puo_gestire_macchine(): admin e operatori).
-- La sezione Ordini nell'app per ora la vede solo l'admin (ORDINI_RUOLI in app.js).
--
-- Come si usa: Supabase > SQL Editor > New query, incolla tutto e premi Run.
-- Si puo' rieseguire senza problemi.
-- ============================================================

create table if not exists public.macchine_of_sezioni (
    id          bigint generated by default as identity primary key,
    marchio     text not null,
    nome        text not null,
    note        text,
    chiusa      boolean not null default false,   -- sezione finita: si vede in fondo, in grigio
    created_at  timestamptz not null default now(),
    created_by  text,
    unique (marchio, nome)
);

create table if not exists public.macchine_of_ordini (
    id          bigint generated by default as identity primary key,
    marchio     text not null,
    sezione_id  bigint references public.macchine_of_sezioni(id) on delete set null,  -- vuoto = ORDINI NORMALE
    data        date not null default current_date,
    operatore   text not null,                    -- iniziali di chi ha fatto l'ordine (es. DZ)
    consegna    text,                             -- es. CONSEGNA GENNAIO 2027 (prestagionali)
    note        text,
    created_at  timestamptz not null default now(),
    created_by  text,
    updated_at  timestamptz not null default now(),
    updated_by  text
);

create index if not exists macchine_of_ordini_marchio_idx on public.macchine_of_ordini (marchio);

alter table public.macchine_pezzi add column if not exists ordine_fornitore_id bigint
    references public.macchine_of_ordini(id) on delete set null;
create index if not exists macchine_pezzi_of_idx on public.macchine_pezzi (ordine_fornitore_id);

-- ------------------------------------------------------------
-- CHI PUO' VEDERE E MODIFICARE
-- ------------------------------------------------------------
alter table public.macchine_of_sezioni enable row level security;
alter table public.macchine_of_ordini enable row level security;

drop policy if exists "macchine_of_sezioni_tutto" on public.macchine_of_sezioni;
create policy "macchine_of_sezioni_tutto" on public.macchine_of_sezioni
    for all to authenticated
    using (public.puo_gestire_macchine())
    with check (public.puo_gestire_macchine());

drop policy if exists "macchine_of_ordini_tutto" on public.macchine_of_ordini;
create policy "macchine_of_ordini_tutto" on public.macchine_of_ordini
    for all to authenticated
    using (public.puo_gestire_macchine())
    with check (public.puo_gestire_macchine());

-- ------------------------------------------------------------
-- CONTROLLO FINALE (deve restituire 3 righe)
-- ------------------------------------------------------------
select 'tabella ' || table_name as controllo from information_schema.tables
where table_schema = 'public' and table_name in ('macchine_of_sezioni', 'macchine_of_ordini')
union all
select 'colonna macchine_pezzi.' || column_name from information_schema.columns
where table_schema = 'public' and table_name = 'macchine_pezzi' and column_name = 'ordine_fornitore_id';
