-- ============================================================
-- AGRIDESK v8.4.0 - MACCHINE IN CONTO ESPOSIZIONE presso collaboratori / altri negozi
-- ------------------------------------------------------------
-- macchine_collaboratori: elenco fisso dei collaboratori (si compila dall'app man mano).
-- macchine_pezzi.esposizione_id / esposizione_dal: la macchina (IN CASA, senza cliente) e' presso
--   quel collaboratore da quella data. Resta NOSTRA: conta nell'inventario e nel valore di magazzino,
--   ma NON e' disponibile alla vendita (quadratino giallo nel quaderno).
-- Permessi come il resto dell'inventario macchine (puo_gestire_macchine: admin e operatori).
--
-- Come si usa: Supabase > SQL Editor > New query, incolla tutto e premi Run. Si puo' rieseguire.
-- ============================================================

create table if not exists public.macchine_collaboratori (
    id          bigint generated by default as identity primary key,
    nome        text not null unique,
    note        text,
    created_at  timestamptz not null default now(),
    created_by  text
);

alter table public.macchine_pezzi add column if not exists esposizione_id bigint
    references public.macchine_collaboratori(id) on delete restrict;
alter table public.macchine_pezzi add column if not exists esposizione_dal date;
create index if not exists macchine_pezzi_esposizione_idx on public.macchine_pezzi (esposizione_id);

alter table public.macchine_collaboratori enable row level security;
drop policy if exists "macchine_collaboratori_tutto" on public.macchine_collaboratori;
create policy "macchine_collaboratori_tutto" on public.macchine_collaboratori
    for all to authenticated
    using (public.puo_gestire_macchine())
    with check (public.puo_gestire_macchine());

-- Controllo
select c.nome, count(p.id) as macchine_in_esposizione
from public.macchine_collaboratori c
left join public.macchine_pezzi p on p.esposizione_id = c.id and p.stato = 'IN_CASA'
group by c.nome order by c.nome;
