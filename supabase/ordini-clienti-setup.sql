-- ============================================================
-- AGRIDESK / AGRIMAG - ORDINI CLIENTI (commissioni)
-- ------------------------------------------------------------
-- Richiede che sia gia' stato eseguito inventario-macchine-setup.sql
--
--   macchine_ordini        testata dell'ordine (numero progressivo per anno, dati cliente,
--                          operatore, firma, link del PDF su Google Drive)
--   macchine_ordini_righe  righe dell'ordine (articolo del listino oppure riga libera)
--   macchine_pezzi         + colonna ordine_riga_id (la macchina del quaderno legata alla riga)
--
-- Il numero riparte da 1 ogni anno solare (es. 2026/1, 2026/2 ... 2027/1).
-- Lo stato dell'ordine NON si salva: l'app lo calcola dai pezzi collegati
-- (da ordinare -> ordinato -> in casa -> consegnato). Si salvano solo
-- annullato_at e consegnato_at (per gli ordini con sole righe libere).
--
-- Come si usa: Supabase > SQL Editor > New query, incolla tutto
-- e premi Run. Si puo' rieseguire senza problemi.
-- ============================================================

create table if not exists public.macchine_ordini (
    id              bigint generated by default as identity primary key,
    anno            integer not null,
    numero          integer not null,
    data            date not null default current_date,
    cliente         text not null,
    indirizzo       text,
    telefono        text,
    email           text,
    codice_fiscale  text,
    partita_iva     text,
    note            text,
    pagamento       text,
    totale          numeric(12,2),
    firma           text,              -- immagine della firma (PNG in base64)
    consegnato_at   timestamptz,
    annullato_at    timestamptz,
    created_at      timestamptz not null default now(),
    created_by      text,
    updated_at      timestamptz not null default now(),
    updated_by      text,
    unique (anno, numero)
);

create table if not exists public.macchine_ordini_righe (
    id              bigint generated by default as identity primary key,
    ordine_id       bigint not null references public.macchine_ordini(id) on delete cascade,
    posizione       integer not null default 1,
    articolo_id     bigint references public.listino_articoli(id) on delete set null, -- vuoto = riga libera
    descrizione     text not null,
    codice          text,
    quantita        integer not null default 1 check (quantita between 1 and 999),
    prezzo_totale   numeric(12,2),
    disponibilita   text not null default 'LIBERA'
                    check (disponibilita in ('DISPONIBILE', 'DA_ORDINARE', 'LIBERA')),
    created_at      timestamptz not null default now()
);

create index if not exists macchine_ordini_righe_ordine_idx on public.macchine_ordini_righe (ordine_id);

-- Colonne aggiunte dopo (si possono rieseguire: se ci sono gia' non succede nulla)
alter table public.macchine_ordini add column if not exists operatore text;          -- chi ha fatto il contratto
alter table public.macchine_ordini add column if not exists drive_url text;          -- PDF salvato su Google Drive
alter table public.macchine_ordini add column if not exists drive_file_id text;
alter table public.macchine_ordini add column if not exists drive_salvato_at timestamptz;
-- Ordine "senza servizio di installazione" (robot e prodotti montati dal cliente): seconda dichiarazione con firma propria
alter table public.macchine_ordini add column if not exists senza_installazione boolean not null default false;
alter table public.macchine_ordini add column if not exists firma_installazione text;   -- PNG base64

-- Collegamento macchina del quaderno -> riga dell'ordine
alter table public.macchine_pezzi add column if not exists ordine_riga_id bigint
    references public.macchine_ordini_righe(id) on delete set null;
create index if not exists macchine_pezzi_ordine_idx on public.macchine_pezzi (ordine_id);

-- ------------------------------------------------------------
-- CHI PUO' VEDERE E MODIFICARE: come l'inventario macchine
-- (funzione puo_gestire_macchine(), per ora solo admin)
-- ------------------------------------------------------------
alter table public.macchine_ordini enable row level security;
alter table public.macchine_ordini_righe enable row level security;

drop policy if exists "macchine_ordini_tutto" on public.macchine_ordini;
create policy "macchine_ordini_tutto" on public.macchine_ordini
    for all to authenticated
    using (public.puo_gestire_macchine())
    with check (public.puo_gestire_macchine());

drop policy if exists "macchine_ordini_righe_tutto" on public.macchine_ordini_righe;
create policy "macchine_ordini_righe_tutto" on public.macchine_ordini_righe
    for all to authenticated
    using (public.puo_gestire_macchine())
    with check (public.puo_gestire_macchine());

-- ------------------------------------------------------------
-- CONTROLLO FINALE (deve restituire 2 righe)
-- ------------------------------------------------------------
select table_name from information_schema.tables
where table_schema = 'public'
  and table_name in ('macchine_ordini', 'macchine_ordini_righe')
order by table_name;
