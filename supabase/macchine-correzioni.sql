-- ========================================
-- AGRIDESK - Inventario Macchine: CORREZIONE INVENTARIO (solo admin)
-- Da eseguire UNA volta su Supabase > SQL Editor (si puo' rieseguire: non rompe niente).
--
-- Serve a togliere una macchina caricata per errore come se non fosse mai entrata:
--   - la riga del quaderno viene cancellata
--   - spariscono anche i suoi movimenti (carico ecc.): nei Movimenti e nei report non resta niente
--   - tutto (macchina + movimenti tolti) viene copiato nel registro macchine_correzioni,
--     che vede SOLO l'admin (scheda "Correzioni" dell'Inventario Macchine)
-- Si possono togliere solo macchine IN CASA, non assegnate a un cliente e non legate a un ordine.
-- Funzione separata: le funzioni gia' esistenti non vengono toccate.
-- ========================================

create table if not exists public.macchine_correzioni (
    id            bigint generated by default as identity primary key,
    created_at    timestamptz not null default now(),
    utente        text,
    tipo          text not null default 'TOLTA',
    pezzo_id      bigint,
    articolo_id   bigint,
    descrizione   text,          -- marchio modello note (com'era nel listino in quel momento)
    matricola     text,
    netto         numeric(12,2),
    data_carico   timestamptz,
    codice_letto  text,          -- codice letto col lettore (matricola o codice a barre), se c'era
    motivo        text,
    pezzo         jsonb,         -- copia completa della riga cancellata
    movimenti     jsonb          -- copia dei movimenti cancellati
);
create index if not exists macchine_correzioni_data_idx on public.macchine_correzioni (created_at desc);

alter table public.macchine_correzioni enable row level security;

-- Lettura solo admin. Nessuno scrive o cancella direttamente: solo la funzione qui sotto.
drop policy if exists "macchine_correzioni_lettura_admin" on public.macchine_correzioni;
create policy "macchine_correzioni_lettura_admin" on public.macchine_correzioni
    for select to authenticated using (public.is_admin());

create or replace function public.macchine_correzione_togli(p_pezzo_id bigint, p_codice text, p_motivo text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
    v_p     public.macchine_pezzi%rowtype;
    v_descr text;
    v_mov   jsonb;
begin
    if not public.is_admin() then
        raise exception 'Solo l''admin puo'' correggere l''inventario';
    end if;

    select * into v_p from public.macchine_pezzi where id = p_pezzo_id for update;
    if not found then
        raise exception 'Macchina non trovata (forse e'' gia'' stata tolta)';
    end if;
    if v_p.stato <> 'IN_CASA' then
        raise exception 'Si possono togliere solo macchine in casa';
    end if;
    if coalesce(trim(v_p.cliente), '') <> '' then
        raise exception 'La macchina e'' assegnata al cliente %: toglila prima dal cliente', v_p.cliente;
    end if;
    if v_p.ordine_id is not null then
        raise exception 'La macchina e'' legata a un ordine cliente';
    end if;

    select trim(concat_ws(' ', a.marchio, a.modello, a.note)) into v_descr
    from public.listino_articoli a where a.id = v_p.articolo_id;

    select coalesce(jsonb_agg(to_jsonb(m) order by m.id), '[]'::jsonb) into v_mov
    from public.macchine_movimenti m where m.pezzo_id = v_p.id;

    insert into public.macchine_correzioni
        (utente, tipo, pezzo_id, articolo_id, descrizione, matricola, netto, data_carico, codice_letto, motivo, pezzo, movimenti)
    values
        (coalesce(auth.jwt() ->> 'email', ''), 'TOLTA', v_p.id, v_p.articolo_id, v_descr, v_p.matricola, v_p.netto_carico,
         v_p.data_carico, nullif(trim(coalesce(p_codice, '')), ''), nullif(trim(coalesce(p_motivo, '')), ''), to_jsonb(v_p), v_mov);

    delete from public.macchine_movimenti where pezzo_id = v_p.id;
    delete from public.macchine_pezzi where id = v_p.id;

    return coalesce(v_descr, 'MACCHINA');
end;
$$;

revoke all on function public.macchine_correzione_togli(bigint, text, text) from public;
grant execute on function public.macchine_correzione_togli(bigint, text, text) to authenticated;
