-- ============================================================
-- AGRIDESK / AGRIMAG - INVENTARIO MACCHINE (fase 1)
-- ------------------------------------------------------------
-- Crea le tabelle dell'inventario macchine collegato al Listino Vendite:
--   macchine_pezzi        una riga per OGNI macchina fisica (come un quadratino del quadernone)
--   macchine_composizione di cosa e' fatto un SET (es. SET BGA110 = BGA110 + AP30 + AL101)
--   macchine_movimenti    registro di carichi, modifiche e cancellazioni (servira' ai report)
--
-- Stati di un pezzo (i colori del quadernone):
--   DA_ORDINARE  quadrato BIANCO + nome cliente  (venduta, non ancora ordinata al fornitore)
--   ORDINATA     quadrato BLU + nome cliente     (ordinata al fornitore per quel cliente)
--   IN_CASA      quadrato VERDE                  (con nome = assegnata, senza nome = disponibile)
--   CONSEGNATA   quadrato VERDE con la croce     (consegnata al cliente)
--
-- Come si usa: Supabase > SQL Editor > New query, incolla tutto
-- e premi Run. Si puo' rieseguire senza problemi.
-- ============================================================

-- ------------------------------------------------------------
-- 1. PEZZI (una riga per macchina fisica)
-- ------------------------------------------------------------
create table if not exists public.macchine_pezzi (
    id             bigint generated by default as identity primary key,
    articolo_id    bigint not null references public.listino_articoli(id) on delete restrict,
    stato          text not null default 'IN_CASA'
                   check (stato in ('DA_ORDINARE', 'ORDINATA', 'IN_CASA', 'CONSEGNATA')),
    cliente        text,                 -- vuoto + IN_CASA = disponibile alla vendita
    matricola      text,                 -- facoltativa (si inserisce quando la macchina e' in casa)
    netto_carico   numeric(12,2),        -- netto 1 al momento del carico (per il valore di magazzino)
    set_id         bigint references public.listino_articoli(id) on delete set null, -- se venduta dentro un SET
    ordine_id      bigint,               -- servira' con gli ordini/commissioni (fase 3)
    note           text,
    data_carico    timestamptz,          -- quando e' entrata in casa
    data_consegna  timestamptz,          -- quando e' stata consegnata
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now(),
    updated_by     text
);

create index if not exists macchine_pezzi_articolo_idx on public.macchine_pezzi (articolo_id);
create index if not exists macchine_pezzi_stato_idx on public.macchine_pezzi (stato);

-- ------------------------------------------------------------
-- 2. COMPOSIZIONE DEI SET
--    set_id = articolo del listino che e' un set
--    componente_id = articolo del listino che fa parte del set
-- ------------------------------------------------------------
create table if not exists public.macchine_composizione (
    set_id         bigint not null references public.listino_articoli(id) on delete cascade,
    componente_id  bigint not null references public.listino_articoli(id) on delete restrict,
    quantita       integer not null default 1 check (quantita between 1 and 99),
    created_at     timestamptz not null default now(),
    primary key (set_id, componente_id),
    check (set_id <> componente_id)
);

-- ------------------------------------------------------------
-- 3. MOVIMENTI (registro)
--    tipo: CARICO / NUOVA VOCE / MODIFICA / CANCELLATA
-- ------------------------------------------------------------
create table if not exists public.macchine_movimenti (
    id           bigint generated by default as identity primary key,
    created_at   timestamptz not null default now(),
    pezzo_id     bigint,               -- niente vincolo: il movimento resta anche se il pezzo viene cancellato
    articolo_id  bigint,
    tipo         text not null,
    stato_prima  text,
    stato_dopo   text,
    cliente      text,
    matricola    text,
    netto        numeric(12,2),
    dettaglio    text,
    utente       text
);

create index if not exists macchine_movimenti_data_idx on public.macchine_movimenti (created_at desc);
create index if not exists macchine_movimenti_articolo_idx on public.macchine_movimenti (articolo_id);

-- ------------------------------------------------------------
-- 4. CHI PUO' VEDERE E MODIFICARE
--    Admin e operatori (tabella user_roles), non i tecnici.
--    (Per tornare a solo admin: role in ('admin') e rieseguire solo questa funzione)
-- ------------------------------------------------------------
create or replace function public.puo_gestire_macchine()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1 from public.user_roles
        where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
          and role in ('admin', 'operatore')
    );
$$;

alter table public.macchine_pezzi enable row level security;
alter table public.macchine_composizione enable row level security;
alter table public.macchine_movimenti enable row level security;

drop policy if exists "macchine_pezzi_tutto" on public.macchine_pezzi;
create policy "macchine_pezzi_tutto" on public.macchine_pezzi
    for all to authenticated
    using (public.puo_gestire_macchine())
    with check (public.puo_gestire_macchine());

drop policy if exists "macchine_composizione_tutto" on public.macchine_composizione;
create policy "macchine_composizione_tutto" on public.macchine_composizione
    for all to authenticated
    using (public.puo_gestire_macchine())
    with check (public.puo_gestire_macchine());

-- Movimenti: si leggono e si aggiungono, NON si modificano e NON si cancellano
drop policy if exists "macchine_movimenti_lettura" on public.macchine_movimenti;
create policy "macchine_movimenti_lettura" on public.macchine_movimenti
    for select to authenticated using (public.puo_gestire_macchine());
drop policy if exists "macchine_movimenti_inserimento" on public.macchine_movimenti;
create policy "macchine_movimenti_inserimento" on public.macchine_movimenti
    for insert to authenticated with check (public.puo_gestire_macchine());

-- ------------------------------------------------------------
-- 5. CONTROLLO FINALE (deve restituire 3 righe)
-- ------------------------------------------------------------
select table_name from information_schema.tables
where table_schema = 'public'
  and table_name in ('macchine_pezzi', 'macchine_composizione', 'macchine_movimenti')
order by table_name;
