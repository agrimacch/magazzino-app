create or replace function public.mezzi_puo_gestire()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select public.is_admin();
$$;

-- Cambia la quantita' di un ricambio in un furgone e scrive il movimento.
-- Restituisce quantita' prima, dopo e soglia (all'app servono per l'avviso Telegram).
create or replace function public.mezzi_muovi(
    p_ricambio bigint, p_furgone bigint, p_delta integer, p_tipo text,
    p_rapportino bigint default null, p_nota text default null
)
returns table (quantita_prima integer, quantita_dopo integer, soglia integer)
language plpgsql
security definer
set search_path = public
as $$
declare
    v_prima integer;
    v_soglia integer;
    v_dopo integer;
    v_utente text := coalesce(auth.jwt() ->> 'email', '');
begin
    if not public.mezzi_puo_gestire() then
        raise exception 'Non hai i permessi per il magazzino dei furgoni';
    end if;
    insert into public.mezzi_giacenze (ricambio_id, furgone_id, quantita, soglia)
    values (p_ricambio, p_furgone, 0, 0)
    on conflict (ricambio_id, furgone_id) do nothing;

    select g.quantita, g.soglia into v_prima, v_soglia
    from public.mezzi_giacenze g
    where g.ricambio_id = p_ricambio and g.furgone_id = p_furgone
    for update;

    v_dopo := v_prima + p_delta;
    if v_dopo < 0 then
        raise exception 'QUANTITA_INSUFFICIENTE: nel furgone ce ne sono %', v_prima;
    end if;

    update public.mezzi_giacenze
    set quantita = v_dopo, updated_at = now(), updated_by = v_utente
    where ricambio_id = p_ricambio and furgone_id = p_furgone;

    if p_delta <> 0 then
        insert into public.mezzi_movimenti (ricambio_id, furgone_id, tipo, quantita, quantita_dopo, rapportino_id, nota, utente)
        values (p_ricambio, p_furgone, p_tipo, p_delta, v_dopo, p_rapportino, p_nota, v_utente);
    end if;

    return query select v_prima, v_dopo, v_soglia;
end;
$$;

revoke all on function public.mezzi_muovi(bigint, bigint, integer, text, bigint, text) from public, anon;
grant execute on function public.mezzi_muovi(bigint, bigint, integer, text, bigint, text) to authenticated;

-- Regole di accesso (RLS): tutto a chi puo' gestire
do $$
declare t text;
begin
    foreach t in array array['mezzi_furgoni', 'mezzi_ricambi', 'mezzi_giacenze', 'mezzi_movimenti',
                             'mezzi_rapportini', 'mezzi_rapportini_righe']
    loop
        execute format('alter table public.%I enable row level security', t);
        execute format('drop policy if exists %I on public.%I', t || '_tutto', t);
        execute format('create policy %I on public.%I for all to authenticated using (public.mezzi_puo_gestire()) with check (public.mezzi_puo_gestire())',
                       t || '_tutto', t);
    end loop;
end $$;

-- Tempo reale: se un collega usa o carica un ricambio, le quantita' si aggiornano da sole
do $$
declare t text;
begin
    foreach t in array array['mezzi_ricambi', 'mezzi_giacenze', 'mezzi_rapportini']
    loop
        if not exists (
            select 1 from pg_publication_tables
            where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t
        ) then
            execute format('alter publication supabase_realtime add table public.%I', t);
        end if;
    end loop;
end $$;

