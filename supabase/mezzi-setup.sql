-- I ricambi che i tecnici hanno nei furgoni (CITROEN e FORD), divisi per marca e modello,
-- con quantita' e soglia di avviso per furgone, e i RAPPORTINI di intervento
-- (cliente, macchina, lavori, manodopera, uscita, ricambi usati, totale).
--
--   mezzi_furgoni           i furgoni (CITROEN, FORD: si possono aggiungere)
--   mezzi_ricambi           il catalogo: marca, modelli compatibili, codice, descrizione, prezzi
--   mezzi_giacenze          quanti ce ne sono in ogni furgone + soglia di avviso
--   mezzi_movimenti         carichi, usi, rettifiche (storico)
--   mezzi_rapportini        i rapportini di intervento (numero per anno: 2026/1, 2026/2 ...)
--   mezzi_rapportini_righe  i ricambi usati in ogni rapportino
--   mezzi_muovi()           cambia la quantita' di un ricambio in un furgone e scrive il movimento
--                           (in un colpo solo: due tecnici insieme non si "pestano i piedi")
--
-- Chi puo' fare cosa (PER ORA): solo admin -> funzione mezzi_puo_gestire().
-- Per aprire anche a operatori e tecnici, piu' avanti, basta eseguire:
--   create or replace function public.mezzi_puo_gestire()
--   returns boolean language sql stable security definer set search_path = public
--   as $f$ select public.is_admin() or public.is_tecnico() or public.puo_gestire_macchine(); $f$;
-- (e nell'app MZ_RUOLI in mezzi-functions.js)
--
-- Come si usa: Supabase > SQL Editor > New query, incolla tutto e Run.
-- Si puo' rieseguire senza problemi (non cancella dati).
-- ============================================================

create table if not exists public.mezzi_furgoni (
    id          bigint generated by default as identity primary key,
    nome        text not null unique,
    ordine      integer not null default 0,
    attivo      boolean not null default true,
    created_at  timestamptz not null default now()
);

insert into public.mezzi_furgoni (nome, ordine) values ('CITROEN', 1), ('FORD', 2)
on conflict (nome) do nothing;

create table if not exists public.mezzi_ricambi (
    id                 bigint generated by default as identity primary key,
    marca              text not null default '',
    modelli            text not null default '',      -- separati da virgola; TUTTI / TUTTE = tutti i modelli della marca
    codice             text,                          -- codice del ricambio
    codice_ean         text,
    codice_easy        text,
    codice_gestionale  text,
    codice_precedente  text,
    codice_barre       text,                          -- per etichette e lettore (vuoto = si usa il codice)
    descrizione        text not null,
    prezzo_ivae        numeric(12,2),                 -- IVA esclusa
    prezzo_ic          numeric(12,2),                 -- IVA compresa (quello che vedono i tecnici)
    note               text,
    attivo             boolean not null default true,
    created_at         timestamptz not null default now(),
    created_by         text,
    updated_at         timestamptz not null default now(),
    updated_by         text
);

-- Niente doppioni: stesso codice (o stesso codice a barre) = stesso ricambio
create unique index if not exists mezzi_ricambi_codice_uq
    on public.mezzi_ricambi (upper(codice)) where codice is not null and codice <> '';
create unique index if not exists mezzi_ricambi_barre_uq
    on public.mezzi_ricambi (codice_barre) where codice_barre is not null and codice_barre <> '';

create table if not exists public.mezzi_giacenze (
    ricambio_id  bigint not null references public.mezzi_ricambi(id) on delete cascade,
    furgone_id   bigint not null references public.mezzi_furgoni(id) on delete cascade,
    quantita     integer not null default 0 check (quantita >= 0),
    soglia       integer not null default 0 check (soglia >= 0),   -- avviso quando si arriva a questa quantita'
    updated_at   timestamptz not null default now(),
    updated_by   text,
    primary key (ricambio_id, furgone_id)
);

create table if not exists public.mezzi_rapportini (
    id                bigint generated by default as identity primary key,
    anno              integer not null,
    numero            integer not null,
    data              date not null default ((now() at time zone 'Europe/Rome')::date),
    cliente           text not null,
    telefono          text,
    indirizzo         text,
    modello           text,
    matricola         text,
    lavori            text,
    ore               numeric(6,2) not null default 0 check (ore >= 0),
    tariffa_oraria    numeric(8,2) not null default 40,      -- IVA esclusa
    iva               numeric(5,2) not null default 22,
    uscita            numeric(10,2) not null default 0 check (uscita >= 0),   -- IVA compresa
    note              text,
    tecnico           text,                                  -- solo per noi: NON va sul PDF del cliente
    furgone_id        bigint references public.mezzi_furgoni(id) on delete set null,
    richiesta_id      bigint references public.richieste_robot(id) on delete set null,   -- richiesta di intervento da cui e' nato
    totale            numeric(12,2),                         -- IVA compresa
    drive_url         text,
    drive_file_id     text,
    drive_salvato_at  timestamptz,
    created_at        timestamptz not null default now(),
    created_by        text,
    updated_at        timestamptz not null default now(),
    updated_by        text,
    unique (anno, numero)
);

-- (se la tabella c'era gia') collegamento alla richiesta di intervento
alter table public.mezzi_rapportini
    add column if not exists richiesta_id bigint references public.richieste_robot(id) on delete set null;

create table if not exists public.mezzi_rapportini_righe (
    id             bigint generated by default as identity primary key,
    rapportino_id  bigint not null references public.mezzi_rapportini(id) on delete cascade,
    posizione      integer not null default 1,
    ricambio_id    bigint references public.mezzi_ricambi(id) on delete set null,  -- vuoto = riga libera (non tocca il furgone)
    furgone_id     bigint references public.mezzi_furgoni(id) on delete set null,
    codice         text,
    descrizione    text not null,
    quantita       integer not null default 1 check (quantita between 1 and 999),
    prezzo_ic      numeric(12,2)                                                   -- prezzo unitario IVA compresa
);

create index if not exists mezzi_rapportini_righe_rap_idx on public.mezzi_rapportini_righe (rapportino_id);

create table if not exists public.mezzi_movimenti (
    id             bigint generated by default as identity primary key,
    ricambio_id    bigint references public.mezzi_ricambi(id) on delete set null,
    furgone_id     bigint references public.mezzi_furgoni(id) on delete set null,
    tipo           text not null check (tipo in ('CARICO', 'USO', 'RESO', 'RETTIFICA', 'IMPORT')),
    quantita       integer not null,              -- + entra nel furgone, - esce
    quantita_dopo  integer,
    rapportino_id  bigint references public.mezzi_rapportini(id) on delete set null,
    nota           text,
    utente         text,
    created_at     timestamptz not null default now()
);

create index if not exists mezzi_movimenti_data_idx on public.mezzi_movimenti (created_at desc);

