-- ============================================================
-- AGRIMAG - TECNICI / INTERVENTI ESTERNI (v5.1.0)
-- ------------------------------------------------------------
-- Crea le tabelle del planning settimanale dei tecnici:
--   tecnici                       elenco tecnici
--   interventi_settimana_tecnici  tecnici aggiunti a UNA sola settimana
--   interventi                    una riga per ogni casella compilata o colorata
--
-- Come si usa: Supabase > SQL Editor > New query, incolla tutto
-- e premi Run. Si puo' rieseguire senza problemi.
-- ============================================================

-- ------------------------------------------------------------
-- 1. TECNICI
--    fisso = true  -> compare in TUTTE le settimane
--    fisso = false -> compare solo nelle settimane in cui viene aggiunto
--    attivo = false -> non compare piu' nelle settimane nuove
--    email / telegram_id: serviranno piu' avanti (ruolo tecnico, Telegram)
-- ------------------------------------------------------------
create table if not exists public.tecnici (
    id           bigint generated by default as identity primary key,
    nome         text not null unique,
    fisso        boolean not null default true,
    attivo       boolean not null default true,
    ordine       integer not null default 0,
    email        text,
    telegram_id  text,
    created_at   timestamptz not null default now()
);

-- ------------------------------------------------------------
-- 2. TECNICI AGGIUNTI A UNA SINGOLA SETTIMANA
--    settimana = data del lunedi'
-- ------------------------------------------------------------
create table if not exists public.interventi_settimana_tecnici (
    settimana   date not null,
    tecnico_id  bigint not null references public.tecnici(id) on delete cascade,
    primary key (settimana, tecnico_id)
);

-- ------------------------------------------------------------
-- 3. INTERVENTI
--    Ogni giorno, per ogni tecnico: 4 righe mattina (M) e 4 pomeriggio (P).
--    Esiste una riga solo se la casella e' compilata o colorata.
-- ------------------------------------------------------------
create table if not exists public.interventi (
    id          bigint generated by default as identity primary key,
    tecnico_id  bigint not null references public.tecnici(id) on delete restrict,
    data        date not null,
    turno       text not null check (turno in ('M', 'P')),
    posizione   smallint not null check (posizione between 1 and 4),
    ora         text,
    tipo        text,                 -- INT / SOP / MONT
    esito       text,                 -- ? / NR / OK / NO
    cliente     text,
    colore      text check (colore is null or colore in ('ROSSO', 'GIALLO', 'VERDE', 'BLU')),
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now(),
    updated_by  text,
    unique (tecnico_id, data, turno, posizione)
);

create index if not exists interventi_data_idx on public.interventi (data);

-- ------------------------------------------------------------
-- 4. CHI PUO' MODIFICARE: admin e operatori (tabella user_roles).
--    Tutti gli utenti collegati possono LEGGERE (servira' al ruolo tecnico).
-- ------------------------------------------------------------
create or replace function public.puo_modificare_interventi()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1 from public.user_roles
        where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
          and role in ('admin', 'operatore')
    );
$$;

alter table public.tecnici enable row level security;
alter table public.interventi_settimana_tecnici enable row level security;
alter table public.interventi enable row level security;

-- tecnici
drop policy if exists "tecnici_lettura" on public.tecnici;
create policy "tecnici_lettura" on public.tecnici
    for select to authenticated using (true);
drop policy if exists "tecnici_scrittura" on public.tecnici;
create policy "tecnici_scrittura" on public.tecnici
    for all to authenticated
    using (public.puo_modificare_interventi())
    with check (public.puo_modificare_interventi());

-- tecnici aggiunti alla settimana
drop policy if exists "int_sett_tecnici_lettura" on public.interventi_settimana_tecnici;
create policy "int_sett_tecnici_lettura" on public.interventi_settimana_tecnici
    for select to authenticated using (true);
drop policy if exists "int_sett_tecnici_scrittura" on public.interventi_settimana_tecnici;
create policy "int_sett_tecnici_scrittura" on public.interventi_settimana_tecnici
    for all to authenticated
    using (public.puo_modificare_interventi())
    with check (public.puo_modificare_interventi());

-- interventi
drop policy if exists "interventi_lettura" on public.interventi;
create policy "interventi_lettura" on public.interventi
    for select to authenticated using (true);
drop policy if exists "interventi_scrittura" on public.interventi;
create policy "interventi_scrittura" on public.interventi
    for all to authenticated
    using (public.puo_modificare_interventi())
    with check (public.puo_modificare_interventi());

-- ------------------------------------------------------------
-- 5. TEMPO REALE: se un collega modifica, la settimana si aggiorna da sola
-- ------------------------------------------------------------
do $$
declare
    t text;
begin
    foreach t in array array['tecnici', 'interventi_settimana_tecnici', 'interventi'] loop
        if not exists (
            select 1 from pg_publication_tables
            where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t
        ) then
            execute format('alter publication supabase_realtime add table public.%I', t);
        end if;
    end loop;
end $$;

-- ------------------------------------------------------------
-- 6. TECNICI DI PARTENZA (fissi, in tutte le settimane)
--    I nomi si possono cambiare dall'app (pulsante "Tecnici")
-- ------------------------------------------------------------
insert into public.tecnici (nome, fisso, ordine) values
    ('ALESSANDRO ZANON', true, 1),
    ('BUSATO PAOLO', true, 2)
on conflict (nome) do nothing;

-- ------------------------------------------------------------
-- Controllo finale: devono comparire 6 regole e realtime = true
-- ------------------------------------------------------------
select
    p.tablename as tabella,
    p.policyname as regola,
    p.cmd as operazione,
    exists (
        select 1 from pg_publication_tables r
        where r.pubname = 'supabase_realtime' and r.tablename = p.tablename
    ) as realtime
from pg_policies p
where p.tablename in ('tecnici', 'interventi_settimana_tecnici', 'interventi')
order by p.tablename, p.policyname;
