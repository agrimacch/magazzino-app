-- ============================================================
-- AGRIMAG - ASSENZE TECNICI DA GOOGLE CALENDAR (v5.1.0)
-- ------------------------------------------------------------
-- Tabella "assenze_eventi": gli eventi di assenza letti dal calendario
-- condiviso, con il tecnico riconosciuto, i giorni/mezze giornate e lo
-- stato della conferma su Telegram:
--   PROPOSTA          messaggio mandato, in attesa di Si'/No
--   COLORATO          confermato: righe rosse nel planning
--   RIFIUTATO         risposto No
--   NON_RICONOSCIUTO  nessun tecnico (o piu' tecnici possibili) nel titolo
--   CANCELLATO        evento tolto dal calendario
-- La usa solo la funzione Supabase "assenze-tecnici" (chiave di servizio):
-- l'app non la legge, quindi nessuna regola di accesso per gli utenti.
--
-- Va eseguito DOPO interventi-esterni-setup.sql.
-- Come si usa: Supabase > SQL Editor > New query, incolla tutto
-- e premi Run. Si puo' rieseguire senza problemi.
-- ============================================================

create table if not exists public.assenze_eventi (
    id               bigint generated by default as identity primary key,
    evento_id        text not null unique,      -- id dell'evento Google
    firma            text not null,             -- titolo + orari: se cambia = evento modificato
    titolo           text,
    tutto_giorno     boolean not null default false,
    inizio           text,                      -- "2026-11-05" oppure "2026-11-05T16:00" (ora italiana)
    fine             text,
    data_inizio      date,
    data_fine        date,
    tecnico_ids      jsonb not null default '[]'::jsonb,
    tecnici_nomi     text,
    giorni           jsonb not null default '[]'::jsonb,   -- [{ "data": "2026-11-05", "parte": "G" | "M" | "P" }]
    stato            text not null default 'PROPOSTA',
    nota             text,
    telegram_msg_id  bigint,
    created_at       timestamptz not null default now(),
    updated_at       timestamptz not null default now()
);

create index if not exists assenze_eventi_data_fine_idx on public.assenze_eventi (data_fine);

-- Sicurezza: RLS attiva e NESSUNA regola = nessun utente dell'app puo' leggerla o scriverla.
-- Solo la funzione Supabase (chiave di servizio) ci lavora.
alter table public.assenze_eventi enable row level security;

-- Controllo finale: deve comparire "assenze_eventi" con rls = true
select relname as tabella, relrowsecurity as rls
from pg_class
where relname = 'assenze_eventi';
