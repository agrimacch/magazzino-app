-- ============================================================
-- AGRIDESK - ASSISTENZA: RICHIESTE INTERVENTI ROBOT (v6.3.0)
-- ------------------------------------------------------------
-- Crea:
--   richieste_robot          le richieste dei clienti (come il foglio Excel
--                            "INTERVENTI ROBOT": OP, data, cognome nome, indirizzo,
--                            telefono, note, urgenza, esito)
--   interventi.richiesta_id  la casella del planning (Interventi esterni)
--                            agganciata a una richiesta
-- e i collegamenti automatici:
--   * planning -> richiesta: l'esito della casella agganciata passa alla richiesta
--       ?  (o senza esito) -> "-"   (organizzato, in attesa di conferma)
--       NR                 -> NR    (non risponde)
--       OK                 -> OK    (confermato: sparisce da mappa e contenitori)
--       NO / casella svuotata / scollegata -> esito vuoto (torna "da organizzare")
--     Una richiesta con esito NO (annullata dall'ufficio) non viene piu' toccata.
--   * ordini clienti -> richiesta: ordine con robot o antizanzare SENZA la spunta
--       "senza servizio di installazione" = richiesta di MONTAGGIO automatica
--       (funzione richieste_robot_da_ordine, chiamata dall'app dopo il salvataggio).
--       Ordine annullato / eliminato / spunta messa: la richiesta non ancora
--       organizzata viene tolta.
--
-- Chi puo' fare cosa (PER ORA):
--   leggere   : tutti gli utenti collegati (ai tecnici serve per i link
--               telefono / Google Maps nel planning)
--   scrivere  : solo admin  -> funzione richieste_robot_puo_modificare()
--
-- QUANDO LE SEZIONI SARANNO PRONTE (admin + operatori possono scrivere)
-- basta eseguire queste righe (le trovi anche in fondo al file):
--   create or replace function public.richieste_robot_puo_modificare()
--   returns boolean language sql stable security definer set search_path = public
--   as $f$ select public.puo_modificare_interventi(); $f$;
--
-- Richiede: interventi-esterni-setup.sql, ordini-clienti-setup.sql,
--           funzione is_admin() (gia' presente).
-- Come si usa: Supabase > SQL Editor > New query, incolla tutto e premi Run.
-- Si puo' rieseguire senza problemi (non cancella dati).
-- ============================================================

-- ------------------------------------------------------------
-- 1. TABELLA RICHIESTE
-- ------------------------------------------------------------
create table if not exists public.richieste_robot (
    id             bigint generated by default as identity primary key,
    data           date not null default ((now() at time zone 'Europe/Rome')::date),  -- data della chiamata
    operatore      text,                       -- chi ha raccolto la chiamata (iniziali)
    cliente        text not null,              -- COGNOME NOME
    indirizzo      text not null default '',
    paese          text,                       -- paese (dal suggerimento indirizzo o scritto a mano)
    telefono       text not null default '',
    note           text,                       -- la richiesta del cliente
    tipo           text not null default 'INT' check (tipo in ('INT', 'SOP', 'MONT')),
    urgenza        smallint check (urgenza is null or urgenza between 1 and 99),  -- U1 = in giornata, Un = n giorni lavorativi
    esito          text check (esito is null or esito in ('-', 'OK', 'NR', 'NO')),
    lat            double precision,           -- posizione sulla mappa (OpenStreetMap)
    lon            double precision,
    geo_stato      text,                       -- OK / NON_TROVATO (null = ancora da cercare)
    geo_indirizzo  text,                       -- indirizzo usato per la ricerca (se cambia si rifa')
    ordine_id      bigint unique references public.macchine_ordini(id) on delete set null,
    created_at     timestamptz not null default now(),
    created_by     text,
    updated_at     timestamptz not null default now(),
    updated_by     text
);

create index if not exists richieste_robot_data_idx on public.richieste_robot (data);
create index if not exists richieste_robot_esito_idx on public.richieste_robot (esito);

-- ------------------------------------------------------------
-- 2. CASELLA DEL PLANNING AGGANCIATA A UNA RICHIESTA
-- ------------------------------------------------------------
alter table public.interventi
    add column if not exists richiesta_id bigint references public.richieste_robot(id) on delete set null;
create index if not exists interventi_richiesta_idx on public.interventi (richiesta_id);

-- ------------------------------------------------------------
-- 3. CHI PUO' MODIFICARE LE RICHIESTE (per ora: solo admin)
-- ------------------------------------------------------------
create or replace function public.richieste_robot_puo_modificare()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select public.is_admin();
$$;

alter table public.richieste_robot enable row level security;

drop policy if exists "richieste_robot_lettura" on public.richieste_robot;
create policy "richieste_robot_lettura" on public.richieste_robot
    for select to authenticated using (true);

drop policy if exists "richieste_robot_inserimento" on public.richieste_robot;
create policy "richieste_robot_inserimento" on public.richieste_robot
    for insert to authenticated with check (public.richieste_robot_puo_modificare());

drop policy if exists "richieste_robot_modifica" on public.richieste_robot;
create policy "richieste_robot_modifica" on public.richieste_robot
    for update to authenticated
    using (public.richieste_robot_puo_modificare())
    with check (public.richieste_robot_puo_modificare());

drop policy if exists "richieste_robot_cancellazione" on public.richieste_robot;
create policy "richieste_robot_cancellazione" on public.richieste_robot
    for delete to authenticated using (public.richieste_robot_puo_modificare());

-- ------------------------------------------------------------
-- 4. ESITO DAL PLANNING ALLA RICHIESTA
--    Conta l'ultima casella agganciata non annullata (esito diverso da NO).
-- ------------------------------------------------------------
create or replace function public.richieste_robot_ricalcola(p_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    attuale text;
    v text;
    trovato boolean;
    nuovo text;
begin
    if p_id is null then return; end if;
    select esito into attuale from public.richieste_robot where id = p_id;
    if not found then return; end if;
    if attuale = 'NO' then return; end if;      -- annullata dall'ufficio: non si tocca

    select i.esito into v
    from public.interventi i
    where i.richiesta_id = p_id and coalesce(i.esito, '') <> 'NO'
    order by i.data desc, i.updated_at desc nulls last
    limit 1;
    trovato := found;

    nuovo := case
        when not trovato then null
        when v = 'OK' then 'OK'
        when v = 'NR' then 'NR'
        else '-'
    end;

    update public.richieste_robot
    set esito = nuovo, updated_at = now(), updated_by = 'PLANNING'
    where id = p_id and esito is distinct from nuovo;
end;
$$;

create or replace function public.interventi_sync_richieste()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if tg_op = 'DELETE' then
        -- Casella svuotata: la richiesta torna da organizzare.
        -- Eccezione: casella con esito OK (es. "Archivia anno"): la richiesta resta OK.
        if old.richiesta_id is not null and coalesce(old.esito, '') <> 'OK' then
            perform public.richieste_robot_ricalcola(old.richiesta_id);
        end if;
        return old;
    end if;
    if tg_op = 'UPDATE' and old.richiesta_id is not null and old.richiesta_id is distinct from new.richiesta_id then
        perform public.richieste_robot_ricalcola(old.richiesta_id);
    end if;
    if new.richiesta_id is not null then
        perform public.richieste_robot_ricalcola(new.richiesta_id);
    end if;
    return new;
end;
$$;

drop trigger if exists interventi_sync_richieste_trg on public.interventi;
create trigger interventi_sync_richieste_trg
    after insert or delete or update of esito, richiesta_id, data on public.interventi
    for each row execute function public.interventi_sync_richieste();

-- ------------------------------------------------------------
-- 5. POSIZIONE SULLA MAPPA
--    L'app cerca l'indirizzo su OpenStreetMap e salva qui il risultato.
--    Possono farlo admin e operatori anche se la richiesta e' "solo admin".
-- ------------------------------------------------------------
create or replace function public.richieste_robot_posizione(
    p_id bigint, p_lat double precision, p_lon double precision,
    p_stato text, p_indirizzo text, p_paese text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
    if not (public.puo_modificare_interventi() or public.richieste_robot_puo_modificare()) then
        raise exception 'Non autorizzato';
    end if;
    update public.richieste_robot
    set lat = p_lat,
        lon = p_lon,
        geo_stato = p_stato,
        geo_indirizzo = p_indirizzo,
        paese = coalesce(nullif(paese, ''), nullif(upper(trim(coalesce(p_paese, ''))), ''))
    where id = p_id;
end;
$$;

-- ------------------------------------------------------------
-- 6. ORDINI CLIENTI -> RICHIESTA DI MONTAGGIO
--    Robot / antizanzare riconosciuti da:
--      - attrezzo (categoria) del listino che contiene ROBOT o ZANZAR
--      - oppure descrizione della riga che contiene ROBOT o ZANZAR
-- ------------------------------------------------------------
create or replace function public.richieste_robot_da_ordine(p_ordine_id bigint)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
    o public.macchine_ordini%rowtype;
    r public.richieste_robot%rowtype;
    descr text;
    serve boolean;
    trovato boolean;
    oggi date := (now() at time zone 'Europe/Rome')::date;
    utente text := coalesce(auth.jwt() ->> 'email', 'ORDINE');
begin
    if not (public.puo_modificare_interventi() or public.richieste_robot_puo_modificare()) then
        raise exception 'Non autorizzato';
    end if;

    select * into o from public.macchine_ordini where id = p_ordine_id;
    trovato := found;

    if trovato then
        select string_agg(distinct coalesce(
                    nullif(trim(concat_ws(' ', a.attrezzo, a.marchio, a.modello)), ''),
                    rg.descrizione), ', ')
        into descr
        from public.macchine_ordini_righe rg
        left join public.listino_articoli a on a.id = rg.articolo_id
        where rg.ordine_id = p_ordine_id
          and (upper(coalesce(a.attrezzo, '')) like '%ROBOT%'
               or upper(coalesce(a.attrezzo, '')) like '%ZANZAR%'
               or upper(coalesce(rg.descrizione, '')) like '%ROBOT%'
               or upper(coalesce(rg.descrizione, '')) like '%ZANZAR%');
    end if;

    serve := trovato and o.id is not null and o.annullato_at is null
             and not coalesce(o.senza_installazione, false) and descr is not null;

    select * into r from public.richieste_robot where ordine_id = p_ordine_id;

    if not serve then
        if r.id is null then return 'NIENTE'; end if;
        if r.esito is null then
            delete from public.richieste_robot where id = r.id;
            return 'TOLTA';
        end if;
        if r.esito in ('-', 'NR') then
            update public.richieste_robot
            set esito = 'NO', updated_at = now(), updated_by = utente
            where id = r.id;
            return 'ANNULLATA';
        end if;
        return 'NIENTE';      -- gia' fatta (OK) o gia' annullata
    end if;

    if r.id is null then
        insert into public.richieste_robot
            (data, operatore, cliente, indirizzo, telefono, note, tipo, ordine_id, created_by, updated_by)
        values
            (oggi, o.operatore, upper(trim(o.cliente)), upper(trim(coalesce(o.indirizzo, ''))),
             trim(coalesce(o.telefono, '')),
             upper('MONTAGGIO ' || descr || ' - ORDINE ' || o.anno || '/' || o.numero),
             'MONT', p_ordine_id, utente, utente);
        return 'CREATA';
    end if;

    -- Gia' presente: aggiorna i dati del cliente se sono cambiati nell'ordine
    update public.richieste_robot
    set cliente = upper(trim(o.cliente)),
        indirizzo = upper(trim(coalesce(o.indirizzo, ''))),
        telefono = trim(coalesce(o.telefono, '')),
        lat = case when indirizzo is distinct from upper(trim(coalesce(o.indirizzo, ''))) then null else lat end,
        lon = case when indirizzo is distinct from upper(trim(coalesce(o.indirizzo, ''))) then null else lon end,
        geo_stato = case when indirizzo is distinct from upper(trim(coalesce(o.indirizzo, ''))) then null else geo_stato end,
        updated_at = now(),
        updated_by = utente
    where id = r.id
      and (cliente is distinct from upper(trim(o.cliente))
           or indirizzo is distinct from upper(trim(coalesce(o.indirizzo, '')))
           or telefono is distinct from trim(coalesce(o.telefono, '')));
    return 'AGGIORNATA';
end;
$$;

-- Ordine eliminato: la richiesta non ancora organizzata se ne va con lui
create or replace function public.ordini_elimina_richiesta()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    delete from public.richieste_robot where ordine_id = old.id and esito is null;
    return old;
end;
$$;

drop trigger if exists ordini_elimina_richiesta_trg on public.macchine_ordini;
create trigger ordini_elimina_richiesta_trg
    before delete on public.macchine_ordini
    for each row execute function public.ordini_elimina_richiesta();

grant execute on function public.richieste_robot_posizione(bigint, double precision, double precision, text, text, text) to authenticated;
grant execute on function public.richieste_robot_da_ordine(bigint) to authenticated;

-- ------------------------------------------------------------
-- 7. TEMPO REALE: se un collega modifica, le pagine si aggiornano da sole
-- ------------------------------------------------------------
do $$
begin
    if not exists (
        select 1 from pg_publication_tables
        where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'richieste_robot'
    ) then
        alter publication supabase_realtime add table public.richieste_robot;
    end if;
end $$;

-- ------------------------------------------------------------
-- Controllo finale: devono comparire 4 regole con realtime = true
-- ------------------------------------------------------------
select
    p.policyname as regola,
    p.cmd as operazione,
    exists (
        select 1 from pg_publication_tables r
        where r.pubname = 'supabase_realtime' and r.tablename = 'richieste_robot'
    ) as realtime
from pg_policies p
where p.tablename = 'richieste_robot'
order by p.policyname;

